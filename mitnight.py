def get_availability_df(week_type="下週調查表"):
    offset = 0 if week_type == "當週人力" else 1
    week_dates = get_week_dates(offset)
    week_key = week_dates[0][:10]
    db = load_db()
    week_data = db.get("availability", {}).get(week_key, {})

    rows = []
    for d in week_dates:
        attendees = []
        for uname, info in week_data.items():
            if not info.get("absent") and d in info.get("days", []):
                note_str = f" ({info['note']})" if info.get("note") else ""
                attendees.append(f"{uname}{note_str}")
        rows.append([d, "、".join(attendees) if attendees else "（尚無人登記可出席）"])
    return pd.DataFrame(rows, columns=["日期 (星期)", "可出席成員與備註"])

