    if override_name and user_role != "admin":
        return (
            "⛔ 一般成員僅能修改自己的資料！",
            get_availability_df(week_type),
            get_member_avail_records_df(week_type),
            get_week_banner_text(),
            gr.update()
        )

    target_user = override_name if (user_role == "admin" and override_name) else current_user

    offset = 0 if week_type == "當週人力" else 1
    week_dates = get_week_dates(offset)
    week_key = week_dates[0][:10]
