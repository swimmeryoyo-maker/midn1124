def toggle_pin_or_delete(selected_proj_str, action, filter_cat, dist_week_type):
    if not selected_proj_str:
        return "⚠️ 請先選擇項目", get_projects_df(filter_cat), gr.update(), gr.update()
    proj_id = selected_proj_str.split(" - ")[0]
    db = load_db()
    msg = ""
    if action == "pin":
        for p in db["projects"]:
            if p["id"] == proj_id:
                p["pinned"] = not p.get("pinned", False)
                status = "釘選置頂" if p["pinned"] else "取消釘選"
                msg = f"📌 已將「{p['title']}」{status}！"
                break
    elif action == "delete":
        db["projects"] = [p for p in db["projects"] if p["id"] != proj_id]
        msg = f"🗑️ 已刪除項目 {proj_id}！"
    save_db(db)
    choices = get_project_choices()
    first_choice = choices[0] if choices else None
    return (
        msg,
        get_projects_df(filter_cat),
        gr.update(choices=choices, value=first_choice),
        check_segment_distribution(first_choice, dist_week_type)
    )

