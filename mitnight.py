def check_segment_distribution(selected_proj_str, week_type):
    cols = ["日期 (星期)", "A melo", "B melo", "C melo", "Last"]
    if not selected_proj_str:
        return pd.DataFrame(columns=cols)
    proj_id = selected_proj_str.split(" - ")[0]
    db = load_db()
    proj = next((p for p in db.get("projects", []) if p["id"] == proj_id), None)
    if not proj:
        return pd.DataFrame(columns=cols)

    offset = 0 if week_type == "當週人力" else 1
    week_dates = get_week_dates(offset)
    week_key = week_dates[0][:10]
    week_data = db.get("availability", {}).get(week_key, {})

    seg_a = parse_names_to_list(proj.get("a_melo", ""))
    seg_b = parse_names_to_list(proj.get("b_melo", ""))
    seg_c = parse_names_to_list(proj.get("c_melo", ""))
    seg_last = parse_names_to_list(proj.get("last", ""))

    def eval_status(req_members, available_set):
        if not req_members:
            return "⚪ 未設定"
        if all(m in available_set for m in req_members):
            return f"🟢 全到 ({', '.join(req_members)})"
        missing = [m for m in req_members if m not in available_set]
        return f"⚪ 缺: {', '.join(missing)}"

    rows = []
    for d in week_dates:
        avail_today = {uname for uname, info in week_data.items() if not info.get("absent") and d in info.get("days", [])}
        rows.append([
            d[5:],
            eval_status(seg_a, avail_today),
            eval_status(seg_b, avail_today),
            eval_status(seg_c, avail_today),
            eval_status(seg_last, avail_today)
        ])
    return pd.DataFrame(rows, columns=cols)

